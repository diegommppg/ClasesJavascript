let numero1 = 10;
let numero2 = 5; 

//Suma: +
let suma = numero1 + numero2;
//console.log(numero1 + numero2);
console.log("La suma es: " + suma);

//Incremento: ++
numero1++; //numero1 = numero1 + 1
console.log("El incremento es: " + numero1);

//Decremento: --
numero2--; //numero2 = numero2 - 1
console.log("El decremento es: " + numero2);

//Resta: -
let resta = numero1 - numero2;
console.log("La resta es: " + resta);

//Multiplicación: *
let multiplicacion = numero1 * numero2;
console.log("La multiplicación es: " + multiplicacion);

//División: /
let division = numero1 / numero2;
console.log("La división es: " + division);

//Elevar a la potencia: **
console.log("2 elevado a la 3 es: " + (2 ** 3));

//Resto/Módulo: %
console.log("El resto de 10 dividido por 3 es: " + (10 % 3));



